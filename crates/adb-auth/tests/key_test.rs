use rsa::traits::PublicKeyParts;
use std::env;
use std::fs;
use std::process::Command;
use tempfile::TempDir;

#[test]
fn test_generate_key_creates_both_files_and_correct_permissions() {
    let temp_dir = TempDir::new().unwrap();
    let key_path = temp_dir.path().join("adbkey");

    // Generate key using adb_auth_keygen
    adb_auth::adb_auth_keygen(&key_path).expect("Failed to generate key");

    assert!(key_path.exists(), "adbkey should exist");
    let pub_path = temp_dir.path().join("adbkey.pub");
    assert!(pub_path.exists(), "adbkey.pub should exist");

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let metadata = fs::metadata(&key_path).unwrap();
        let mode = metadata.permissions().mode() & 0o777;
        assert_eq!(
            mode, 0o600,
            "adbkey file permission should be 0600 on Unix, got {:o}",
            mode
        );
    }
}

#[test]
fn test_rust_loads_key_generated_by_reference_adb() {
    let reference_adb = match env::var("ADB_REFERENCE") {
        Ok(val) if !val.is_empty() => val,
        _ => {
            let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
            format!("{}/../../binaries/linux/adb", manifest_dir)
        }
    };

    if !std::path::Path::new(&reference_adb).exists() {
        eprintln!(
            "Skipping test: ADB reference binary not found at {}",
            reference_adb
        );
        return;
    }

    let temp_dir = TempDir::new().unwrap();
    let key_path = temp_dir.path().join("adbkey");

    // Run `$ADB_REFERENCE keygen <key_path>`
    let status = Command::new(&reference_adb)
        .arg("keygen")
        .arg(&key_path)
        .status()
        .expect("Failed to run adb keygen");
    assert!(status.success(), "adb keygen failed");

    // Rust adb-auth loads key generated by reference ADB
    let loaded_key = adb_auth::read_key_file(&key_path).expect("Failed to load reference key");
    assert_eq!(loaded_key.size(), 256, "Key should be 2048-bit RSA");
}

#[test]
fn test_reference_adb_loads_key_generated_by_rust() {
    let reference_adb = match env::var("ADB_REFERENCE") {
        Ok(val) if !val.is_empty() => val,
        _ => {
            let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
            format!("{}/../../binaries/linux/adb", manifest_dir)
        }
    };

    if !std::path::Path::new(&reference_adb).exists() {
        eprintln!(
            "Skipping test: ADB reference binary not found at {}",
            reference_adb
        );
        return;
    }

    let temp_dir = TempDir::new().unwrap();
    let key_path = temp_dir.path().join("adbkey");

    // Rust adb-auth generates key
    adb_auth::adb_auth_keygen(&key_path).expect("Failed to generate Rust key");

    // Run `$ADB_REFERENCE pubkey <key_path>` to verify reference ADB reads the key
    let output = Command::new(&reference_adb)
        .arg("pubkey")
        .arg(&key_path)
        .output()
        .expect("Failed to run adb pubkey");

    assert!(
        output.status.success(),
        "adb pubkey failed on Rust-generated key: {}",
        String::from_utf8_lossy(&output.stderr)
    );

    let pubkey_str = String::from_utf8_lossy(&output.stdout);
    assert!(
        !pubkey_str.trim().is_empty(),
        "pubkey output should not be empty"
    );
}

#[test]
fn test_load_or_generate_behavior() {
    let temp_dir = TempDir::new().unwrap();
    let key_path = temp_dir.path().join("adbkey");

    // First call creates key
    let key1 = adb_auth::load_or_generate(&key_path).expect("First load_or_generate failed");
    assert!(key_path.exists());

    // Second call loads existing key without re-generating
    let key2 = adb_auth::load_or_generate(&key_path).expect("Second load_or_generate failed");
    assert_eq!(
        adb_auth::hash_key(&key1),
        adb_auth::hash_key(&key2),
        "Keys should match when loaded twice"
    );
}

#[test]
fn test_vendor_keys_parsing_and_loading() {
    let temp_dir = TempDir::new().unwrap();
    let file_key = temp_dir.path().join("custom.adb_key");
    adb_auth::adb_auth_keygen(&file_key).expect("Failed to generate custom key");

    let dir_key_dir = temp_dir.path().join("vendor_dir");
    fs::create_dir(&dir_key_dir).unwrap();
    let in_dir_key = dir_key_dir.join("one.adb_key");
    adb_auth::adb_auth_keygen(&in_dir_key).expect("Failed to generate in_dir key");

    let non_adb_key = dir_key_dir.join("ignored.txt");
    fs::write(&non_adb_key, "not a key").unwrap();

    // Set ADB_VENDOR_KEYS
    let env_sep = if cfg!(windows) { ";" } else { ":" };
    let vendor_env = format!(
        "{}{}{}",
        file_key.to_string_lossy(),
        env_sep,
        dir_key_dir.to_string_lossy()
    );

    temp_env::with_var("ADB_VENDOR_KEYS", Some(&vendor_env), || {
        let vendor_paths = adb_auth::get_vendor_keys();
        assert_eq!(vendor_paths.len(), 2);

        let keys = adb_auth::load_vendor_keys();
        assert_eq!(
            keys.len(),
            2,
            "Should load key from file and key from dir ending in .adb_key"
        );
    });
}
